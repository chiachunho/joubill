// Posts the E2E summary to the pull request for the deployed commit, as one
// comment that is updated in place on every run. Runs in CI after the E2E step.
//
// Inputs (environment): GITHUB_TOKEN, GITHUB_REPOSITORY, SHA, PREVIEW_URL, RUN_URL,
// E2E_OUTCOME, NEON_OUTCOME. Set DRY_RUN=1 to print the comment instead of posting.

import { existsSync, readFileSync } from "node:fs";
import { basename } from "node:path";

const MARKER = "<!-- e2e-results -->";
const FOOTER = "_Generated by [Claude Code](https://claude.ai/code)_";
const RESULTS_PATH = "test-results/results.json";
const API = "https://api.github.com";
const BOT_LOGIN = "github-actions[bot]";

const env = process.env;

function stripAnsi(text) {
  return text.replace(/\x1b\[[0-9;]*m/g, "");
}

// Playwright's error text ends in a long call log. Keep what comes before it.
function summarizeError(message) {
  const lines = stripAnsi(message).split("\n");
  const cut = lines.findIndex((line) => line.trim().startsWith("Call log:"));
  return (cut === -1 ? lines : lines.slice(0, cut))
    .map((line) => line.trimEnd())
    .filter(Boolean)
    .join("\n")
    .slice(0, 600)
    .replaceAll("```", "'''");
}

function escapeHtml(text) {
  return text.replaceAll("&", "&amp;").replaceAll("<", "&lt;").replaceAll(">", "&gt;");
}

// Walks Playwright's suite tree and returns one entry per test, with the describe
// titles folded into the test title.
function collectTests(suite, parentFile, titles, out) {
  const file = suite.file ?? parentFile;
  const path =
    suite.title && suite.title !== basename(file ?? "") ? [...titles, suite.title] : titles;
  for (const spec of suite.specs ?? []) {
    for (const test of spec.tests ?? []) {
      const lastResult = test.results?.at(-1);
      out.push({
        file: basename(file ?? "unknown"),
        title: [...path, spec.title].join(" › "),
        status: test.status,
        error: lastResult?.error?.message ? summarizeError(lastResult.error.message) : "",
      });
    }
  }
  for (const child of suite.suites ?? []) collectTests(child, file, path, out);
  return out;
}

function summarize(report) {
  const tests = [];
  for (const suite of report.suites ?? []) collectTests(suite, undefined, [], tests);

  const byFile = new Map();
  const failures = [];
  for (const test of tests) {
    const row = byFile.get(test.file) ?? { passed: 0, failed: 0, skipped: 0, flaky: 0 };
    if (test.status === "unexpected") {
      row.failed += 1;
      failures.push(test);
    } else if (test.status === "skipped") {
      row.skipped += 1;
    } else {
      row.passed += 1;
      if (test.status === "flaky") row.flaky += 1;
    }
    byFile.set(test.file, row);
  }
  return { byFile, failures };
}

function totalsLine(byFile) {
  const total = { passed: 0, failed: 0, skipped: 0, flaky: 0 };
  for (const row of byFile.values()) {
    for (const key of Object.keys(total)) total[key] += row[key];
  }
  const headline = total.failed
    ? `**❌ ${total.passed} passed · ${total.failed} failed**`
    : `**✅ ${total.passed} passed**`;
  const extras = [];
  if (total.skipped) extras.push(`${total.skipped} skipped`);
  if (total.flaky) extras.push(`${total.flaky} flaky`);
  return extras.length ? `${headline} · ${extras.join(" · ")}` : headline;
}

function linksLine(sha, previewUrl, runUrl) {
  const parts = [`Commit \`${sha.slice(0, 7)}\``];
  if (previewUrl) parts.push(`[Preview](${previewUrl})`);
  parts.push(`[Run and report](${runUrl})`);
  return parts.join(" · ");
}

function renderResults({ byFile, failures }, sha, previewUrl, runUrl) {
  const rows = [...byFile.entries()].map(
    ([file, row]) => `| \`${file}\` | ${row.passed} | ${row.failed} |`,
  );
  const lines = [
    MARKER,
    "## 🧪 E2E results (preview)",
    "",
    totalsLine(byFile),
    "",
    "| Spec | Passed | Failed |",
    "|---|---:|---:|",
    ...rows,
  ];

  for (const failure of failures) {
    lines.push(
      "",
      `<details><summary>❌ ${escapeHtml(failure.title)}</summary>`,
      "",
      "```",
      failure.error || "(no error message)",
      "```",
      "</details>",
    );
  }

  lines.push("", linksLine(sha, previewUrl, runUrl), "", "---", FOOTER);
  return lines.join("\n");
}

function renderIncomplete(reason, sha, previewUrl, runUrl) {
  return [
    MARKER,
    "## 🧪 E2E results (preview)",
    "",
    `**⚠️ The E2E run did not produce results.** ${reason}`,
    "",
    linksLine(sha, previewUrl, runUrl),
    "",
    "---",
    FOOTER,
  ].join("\n");
}

function incompleteReason() {
  if (env.NEON_OUTCOME === "failure") {
    return "The Neon database lookup failed, so the tests did not run.";
  }
  return "The test runner exited before writing its report.";
}

async function gh(token, method, path, body) {
  const res = await fetch(`${API}${path}`, {
    method,
    headers: {
      Authorization: `Bearer ${token}`,
      Accept: "application/vnd.github+json",
      "X-GitHub-Api-Version": "2022-11-28",
      ...(body ? { "Content-Type": "application/json" } : {}),
    },
    body: body ? JSON.stringify(body) : undefined,
  });
  if (!res.ok) throw new Error(`${method} ${path} -> ${res.status}: ${await res.text()}`);
  return res.status === 204 ? null : res.json();
}

async function postOrUpdate(token, repo, sha, body) {
  // A deployment only knows its commit, so find the open PR that contains it.
  const pulls = await gh(token, "GET", `/repos/${repo}/commits/${sha}/pulls`);
  const pull = pulls.find((p) => p.state === "open");
  if (!pull) {
    console.log(`No open pull request contains ${sha}; skipping the comment.`);
    return;
  }

  // Page through every comment: the marker comment can sit past the first 100.
  let existing;
  for (let page = 1; !existing; page += 1) {
    const comments = await gh(
      token,
      "GET",
      `/repos/${repo}/issues/${pull.number}/comments?per_page=100&page=${page}`,
    );
    existing = comments.find((c) => c.user?.login === BOT_LOGIN && c.body?.includes(MARKER));
    if (comments.length < 100) break;
  }
  if (existing) {
    await gh(token, "PATCH", `/repos/${repo}/issues/comments/${existing.id}`, { body });
    console.log(`Updated the E2E comment on #${pull.number}.`);
  } else {
    await gh(token, "POST", `/repos/${repo}/issues/${pull.number}/comments`, { body });
    console.log(`Posted the E2E comment on #${pull.number}.`);
  }
}

async function main() {
  const sha = env.SHA;
  const previewUrl = env.PREVIEW_URL ?? "";
  const runUrl = env.RUN_URL ?? "";

  const body = existsSync(RESULTS_PATH)
    ? renderResults(
        summarize(JSON.parse(readFileSync(RESULTS_PATH, "utf8"))),
        sha,
        previewUrl,
        runUrl,
      )
    : renderIncomplete(incompleteReason(), sha, previewUrl, runUrl);

  if (env.DRY_RUN === "1") {
    console.log(body);
    return;
  }

  try {
    await postOrUpdate(env.GITHUB_TOKEN, env.GITHUB_REPOSITORY, sha, body);
  } catch (err) {
    // The E2E step decides pass or fail. A failed comment should not hide that result.
    console.log(`::warning::Could not post the E2E comment: ${err.message}`);
  }
}

await main();
