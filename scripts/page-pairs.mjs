// Pure rules for the Mini App / Web App page pairs (issue #57). CLAUDE.md keeps
// src/app/mini/** and src/app/app/** as hand-maintained copies of the same pages, so an
// edit to one side is easy to make without the other. check-page-pairs.mjs runs these
// rules over a diff and reports the one-sided edits.
//
// The pairs are derived from the path, not listed by hand: a hand-kept table would only
// move the drift into the list, and a page missing from it would go unchecked silently.

const MINI_ROOT = "src/app/mini/";
const APP_ROOT = "src/app/app/";

// The same page in the other tree, or null when the path is in neither tree.
export function counterpartOf(path) {
  if (path.startsWith(MINI_ROOT)) return APP_ROOT + path.slice(MINI_ROOT.length);
  if (path.startsWith(APP_ROOT)) return MINI_ROOT + path.slice(APP_ROOT.length);
  return null;
}

// changes: [{ path, status }] where status is git's "A", "M" or "D".
// exists(path): whether the path is present in the tree the change was made in.
//
// Returns one entry per one-sided edit:
//   reason "unchanged": this side changed and the other copy is still there untouched.
//   reason "missing":   a new page with no counterpart on the other side.
// A path with no counterpart that was merely edited, such as app/SWRProvider.tsx, is
// not reported: that file was never meant to have a mirror.
export function findUnpairedChanges(changes, exists) {
  const changed = new Set(changes.map((change) => change.path));
  const problems = [];
  for (const { path, status } of changes) {
    const counterpart = counterpartOf(path);
    if (counterpart === null || changed.has(counterpart)) continue;
    if (exists(counterpart)) {
      problems.push({ path, counterpart, status, reason: "unchanged" });
    } else if (status === "A") {
      problems.push({ path, counterpart, status, reason: "missing" });
    }
  }
  return problems;
}

// One sentence per problem, used in the PR comment and in the console output.
export function describeProblem({ path, counterpart, status, reason }) {
  if (reason === "missing") {
    return `\`${path}\` is a new page, and the other tree has no \`${counterpart}\`.`;
  }
  if (status === "D") {
    return `\`${path}\` was deleted, but its counterpart \`${counterpart}\` was left in place.`;
  }
  return `\`${path}\` changed, but its counterpart \`${counterpart}\` did not.`;
}

export const COMMENT_MARKER = "<!-- page-pair-check -->";
const FOOTER = "_Generated by [Claude Code](https://claude.ai/code)_";

// The PR comment body. It is always rendered, even with no problems, so an earlier
// warning comment gets replaced by an all-clear instead of going stale.
export function renderComment(problems) {
  if (problems.length === 0) {
    return [
      COMMENT_MARKER,
      "## ✅ Mini App / Web App page pairs",
      "",
      "No page changed on one side only.",
      "",
      "---",
      FOOTER,
    ].join("\n");
  }
  return [
    COMMENT_MARKER,
    "## ⚠️ Mini App / Web App page pairs",
    "",
    "This pull request edits one copy of a page pair and not the other. The two copies are",
    "maintained by hand, so the other side is probably missing the same change.",
    "",
    ...problems.map((problem) => `- ${describeProblem(problem)}`),
    "",
    "If the difference is intentional, ignore this comment. It does not block the pull request.",
    "",
    "---",
    FOOTER,
  ].join("\n");
}
